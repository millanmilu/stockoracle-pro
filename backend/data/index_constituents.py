def resolve_universe(universe_id):
    """Returns the ticker list for a universe id (or alias), or None if unknown."""
    if not universe_id:
        return None
    key = str(universe_id).upper().strip()
    if key in INDEX_CONSTITUENTS:
        return list(INDEX_CONSTITUENTS[key])
    target = UNIVERSE_ALIASES.get(key)
    if target and target in INDEX_CONSTITUENTS:
        return list(INDEX_CONSTITUENTS[target])
    return None


def resolve_query_scope(tickers, universe):
    """Categorical scoping for /screener/query.

    Explicit `tickers` win (sanitized + capped); otherwise `universe` id
    resolves to official constituents; otherwise None (= whole table).
    """
    import re as _re
    if tickers:
        scoped = sorted({
            t.upper().strip() for t in tickers
            if isinstance(t, str) and _re.fullmatch(r"[A-Z0-9.\-]{1,25}", t.upper().strip())
        })[:2000]
        return scoped or None
    if universe:
        return resolve_universe(universe)
    return None


def list_universes():
    """Returns [{id, count, covered}] for every known universe (drives the UI dropdown).

    `covered` = constituents that already have a metrics row in
    screener_daily_metrics; covered < count signals incomplete seed coverage in
    the UI. DB failures degrade gracefully to covered == count.
    """
    universes = [
        {'id': uid, 'count': len(syms), 'covered': len(syms)}
        for uid, syms in INDEX_CONSTITUENTS.items()
        if uid != 'NIFTY NEXT 50'
    ]
    try:
        from sqlalchemy import select as _select
        from backend.shared.database import get_db_session
        from backend.shared.models import ScreenerDailyMetric
        with get_db_session() as session:
            rows = session.execute(_select(ScreenerDailyMetric.ticker)).all()
        available = {str(r[0]).upper().strip() for r in rows}
        for u in universes:
            u['covered'] = sum(1 for t in INDEX_CONSTITUENTS[u['id']] if t in available)
    except Exception:
        pass  # keep covered == count fallback
    return universes
